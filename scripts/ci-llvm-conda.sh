#!/usr/bin/env bash
# Installs LLVM 23 and clang's static libraries for Intel macOS (#129) from conda-forge into
# <prefix>, for LLVM_SYS_231_PREFIX: prebuilt, where Homebrew would compile them for 5 hours.
# The packages are the ones scripts/conda/llvm-osx-64.lock names, by URL and checksum.
#
# Usage: scripts/ci-llvm-conda.sh <prefix>
#        scripts/ci-llvm-conda.sh --relock <prefix>
#          solve scripts/conda/llvm-osx-64.in instead, and print the lock file for that set
set -euo pipefail
relock=0
[ "${1:-}" = --relock ] && { relock=1; shift; }
[ $# -eq 1 ] || { echo "usage: $0 [--relock] <prefix>" >&2; exit 2; }
prefix=$1
conda="$(cd "$(dirname "$0")" && pwd)/conda"
[ "$(uname -s)-$(uname -m)" = Darwin-x86_64 ] || { echo "$0: for Intel macOS" >&2; exit 1; }

# micromamba, pinned: conda-forge's package of it (the channel everything else comes from), a
# single static binary.
mm_pkg=micromamba-2.9.0-0.tar.bz2
mm_sha256=0426ecdc41636d369f57b8fe6acbf4385a69eca45b56d9ee7d3a840a9965d44f
tmp=${RUNNER_TEMP:-${TMPDIR:-/tmp}}
mm="$tmp/micromamba-${mm_pkg%.tar.bz2}/bin/micromamba"
if [ ! -x "$mm" ]; then
  curl -fsSL --retry 10 --retry-all-errors --retry-delay 10 -o "$tmp/$mm_pkg" \
    "https://conda.anaconda.org/conda-forge/osx-64/$mm_pkg"
  echo "$mm_sha256  $tmp/$mm_pkg" | shasum -a 256 -c - > /dev/null
  mkdir -p "$tmp/micromamba-${mm_pkg%.tar.bz2}"
  tar -xjf "$tmp/$mm_pkg" -C "$tmp/micromamba-${mm_pkg%.tar.bz2}" bin/micromamba
  rm "$tmp/$mm_pkg"
fi
export MAMBA_ROOT_PREFIX="$tmp/mamba"

if [ "$relock" = 1 ]; then
  "$mm" create --yes --quiet --prefix "$prefix" --override-channels -c conda-forge --file "$conda/llvm-osx-64.in"
  echo "# Generated by scripts/ci-llvm-conda.sh --relock from llvm-osx-64.in: don't edit."
  "$mm" env export --prefix "$prefix" --explicit --md5 | grep -v '^#'
  exit 0
fi
"$mm" create --yes --quiet --prefix "$prefix" --file "$conda/llvm-osx-64.lock"

# What the build takes from it: llvm-config, LLVM's and clang's static libraries, zstd's, and
# clang's resource headers (embedded in pico).
v=$("$prefix/bin/llvm-config" --version)
for f in lib/libLLVMCore.a lib/libclangDriver.a lib/libzstd.a "lib/clang/${v%%.*}/include/stddef.h"; do
  [ -e "$prefix/$f" ] || { echo "$prefix/$f is missing" >&2; exit 1; }
done
echo "LLVM $v from conda-forge in $prefix"
