#!/usr/bin/env bash
# Regenerates third_party/tzdata (decision 253): the IANA tz database compiled by its own zic
# into compact ("slim") TZif files, packed into tzdata.bin, plus the Windows → IANA zone table
# from CLDR's windowsZones.xml. Programs for targets without a system database link them.
#
#   scripts/update-tzdata.sh 2026f
#
# Needs curl, gpg, a C compiler and python3. The tarballs are checked against the tz
# maintainer's key (Paul Eggert, 7E37 92A9 D8AC F7D6 33BC 1588 ED97 E90E 62AA 7E34).
set -euo pipefail
cd "$(dirname "$0")/.."
version="${1:?usage: $0 <tzdb version, e.g. 2026f>}"
dest=third_party/tzdata
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export GNUPGHOME="$work/gnupg"
mkdir -m 700 "$GNUPGHOME"

base=https://data.iana.org/time-zones/releases
for f in "tzdata$version.tar.gz" "tzcode$version.tar.gz"; do
  curl -sfL -o "$work/$f" "$base/$f"
  curl -sfL -o "$work/$f.asc" "$base/$f.asc"
done
gpg --batch --quiet --keyserver hkps://keyserver.ubuntu.com \
  --recv-keys 7E3792A9D8ACF7D633BC1588ED97E90E62AA7E34
for f in "tzdata$version.tar.gz" "tzcode$version.tar.gz"; do
  gpg --batch --verify "$work/$f.asc" "$work/$f" 2>&1 | grep -q 'Good signature' \
    || { echo "bad signature: $f" >&2; exit 1; }
done

src="$work/src"
mkdir "$src"
tar -xzf "$work/tzdata$version.tar.gz" -C "$src"
tar -xzf "$work/tzcode$version.tar.gz" -C "$src"
make -s -C "$src" zic CC="${CC:-cc}" >/dev/null
zones="$work/zoneinfo"
data="africa antarctica asia australasia europe northamerica southamerica etcetera backward factory"
(cd "$src" && ./zic -b slim -d "$zones" $data)

# CLDR's Windows zone names → IANA ids (the "001" territory: each name's main zone).
curl -sfL -o "$work/windowsZones.xml" \
  https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml

rm -rf "$dest"
mkdir -p "$dest"
python3 -I - "$zones" "$dest" "$version" "$work/windowsZones.xml" <<'PY'
import os, struct, sys, hashlib, xml.etree.ElementTree as ET
zones, dest, version, wz = sys.argv[1:]
names = []
for root, _, files in os.walk(zones):
    for f in files:
        p = os.path.join(root, f)
        with open(p, 'rb') as fh:
            if fh.read(4) != b'TZif':
                continue
        names.append(os.path.relpath(p, zones).replace(os.sep, '/'))
names.sort()
# tzdata.bin: "PPLTZ\0\1\0", u32 count, then per zone (by name) u16 name length, the name,
# u32 offset and u32 length of its TZif bytes (from the start of the file); identical zones
# (links) share their bytes.
blobs, offsets, entries = [], {}, []
header = 8 + 4 + sum(2 + len(n.encode()) + 8 for n in names)
at = header
for n in names:
    b = open(os.path.join(zones, n), 'rb').read()
    h = hashlib.sha256(b).digest()
    if h not in offsets:
        offsets[h] = at
        blobs.append(b)
        at += len(b)
    entries.append((n, offsets[h], len(b)))
with open(os.path.join(dest, 'tzdata.bin'), 'wb') as out:
    out.write(b'PPLTZ\x00\x01\x00' + struct.pack('<I', len(entries)))
    for n, off, ln in entries:
        e = n.encode()
        out.write(struct.pack('<H', len(e)) + e + struct.pack('<II', off, ln))
    for b in blobs:
        out.write(b)
# windows_zones.inc: { L"Windows name", "IANA id" }, sorted by the Windows name.
rows = {}
for m in ET.parse(wz).getroot().iter('mapZone'):
    if m.get('territory') == '001':
        rows[m.get('other')] = m.get('type').split()[0]
with open(os.path.join(dest, 'windows_zones.inc'), 'w') as out:
    out.write('/* Generated by scripts/update-tzdata.sh from CLDR windowsZones.xml. */\n')
    for k in sorted(rows):
        out.write('{L"%s", "%s"},\n' % (k, rows[k]))
with open(os.path.join(dest, 'VERSION'), 'w') as out:
    out.write(version + '\n')
print(f'{len(entries)} zones, {len(blobs)} distinct, {at} bytes; {len(rows)} Windows names')
PY
cp "$src/LICENSE" "$dest/LICENSE.tzdb"
echo "done: $dest (tzdb $version)"
