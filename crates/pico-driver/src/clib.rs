//! The C header of a library built with `pico build --lib` (spec §12.4, decision 263): the
//! `@export("c")` functions' prototypes, with the `@pod` structs their pointers name.

use pico_mir::mir::Program;
use pico_sema::hir::{ExportAbi, StructId};
use pico_sema::ty::{FloatTy, IntTy, Ty};
use std::fmt::Write;

/// The header text; `guard` names its include guard.
pub fn header(p: &Program, guard: &str) -> String {
    let guard: String = guard
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    let mut structs: Vec<StructId> = Vec::new();
    let mut protos = String::new();
    for e in p.exports.iter().filter(|e| e.abi == ExportAbi::C) {
        let params: Vec<String> = e
            .params
            .iter()
            .map(|(n, t)| format!("{} {n}", c_type(t, &mut structs)))
            .collect();
        let params = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        let _ = writeln!(
            protos,
            "{} {}({params});",
            c_type(&e.ret, &mut structs),
            e.name
        );
    }
    let mut defs = String::new();
    // (A struct's fields may name more structs: they're declared before it.)
    let mut done: Vec<StructId> = Vec::new();
    let mut i = 0;
    while i < structs.len() {
        let sid = structs[i];
        i += 1;
        if done.contains(&sid) {
            continue;
        }
        let mut more = Vec::new();
        let mut body = String::new();
        let layout = p.layout(sid);
        for (name, t) in &layout.fields {
            let decl = field(t, name, &mut more);
            let _ = writeln!(body, "    {decl};");
        }
        for m in more {
            if !done.contains(&m) && !structs.contains(&m) {
                structs.push(m);
            }
        }
        let _ = writeln!(defs, "typedef struct {0} {{\n{body}}} {0};\n", layout.name);
        done.push(sid);
    }
    format!(
        "/* Generated by pico (`pico build --lib`): the library's `@export(\"c\")` functions.\n * The first call on a thread starts that thread's pico heap and module instance. */\n#ifndef {guard}_H\n#define {guard}_H\n\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n\n{defs}{protos}\n#ifdef __cplusplus\n}}\n#endif\n\n#endif\n"
    )
}

/// A C declaration of field `name` (fixed arrays put their length after the name).
fn field(t: &Ty, name: &str, structs: &mut Vec<StructId>) -> String {
    match t {
        Ty::Fixed(elem, n) => format!("{} {name}[{n}]", c_type(elem, structs)),
        t => format!("{} {name}", c_type(t, structs)),
    }
}

/// A pico type (one the exports may use) in C.
fn c_type(t: &Ty, structs: &mut Vec<StructId>) -> String {
    match t {
        Ty::Void => "void".into(),
        Ty::Bool => "bool".into(),
        Ty::Int(it) => match it {
            IntTy::I8 => "int8_t",
            IntTy::I16 => "int16_t",
            IntTy::I32 => "int32_t",
            IntTy::I64 => "int64_t",
            IntTy::U8 => "uint8_t",
            IntTy::U16 => "uint16_t",
            IntTy::U32 => "uint32_t",
            IntTy::U64 => "uint64_t",
            IntTy::Isize => "ptrdiff_t",
            IntTy::Usize => "size_t",
        }
        .into(),
        Ty::Float(FloatTy::F32) => "float".into(),
        Ty::Float(_) => "double".into(),
        Ty::Ref(inner) => match &**inner {
            Ty::Fn(..) => "void *".into(),
            inner => format!("{} *", c_type(inner, structs)),
        },
        // `ptr<T>?`: the same C pointer, which may be `NULL`.
        Ty::Nullable(inner) if matches!(**inner, Ty::Ref(_)) => c_type(inner, structs),
        Ty::Struct(sid, name, _) => {
            if !structs.contains(sid) {
                structs.push(*sid);
            }
            name.to_string()
        }
        _ => "void".into(),
    }
}
